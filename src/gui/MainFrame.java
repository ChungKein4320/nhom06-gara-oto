package gui;
import javax.swing.*;
import javax.swing.border.*;
import java.awt.*;
public class MainFrame extends JFrame {
    private final Role role;
    private final JPanel nav,body;
    private final JLabel title;
    private String current="Tổng quan";
    public MainFrame(Role role){
        this.role=role;
        setTitle("Thinking Auto • "+role.title);
        setDefaultCloseOperation(EXIT_ON_CLOSE);
        setSize(1400,860);
        setMinimumSize(new Dimension(1060,680));
        setLocationRelativeTo(null);
        setLayout(new BorderLayout());
        JPanel sidebar=new JPanel(new BorderLayout());
        sidebar.setBackground(Theme.NAV);
        sidebar.setPreferredSize(new Dimension(246,0));
        JPanel brand=new JPanel();
        brand.setBackground(Theme.NAV);
        brand.setBorder(new EmptyBorder(25,18,18,12));
        brand.setLayout(new BoxLayout(brand,BoxLayout.Y_AXIS));
        JLabel logo=Theme.label("Thinking Auto",23,true,Theme.MINT);
        logo.setIcon(Icons.get("phương tiện",23,Theme.MINT));
        logo.setIconTextGap(10);
        brand.add(logo);
        brand.add(Box.createVerticalStrut(5));
        brand.add(Theme.label("QUẢN LÝ GARA  •  GÒ VẤP",10,true,Theme.CREAM));
        sidebar.add(brand,BorderLayout.NORTH);
        nav=new JPanel();
        nav.setBackground(Theme.NAV);
        nav.setBorder(new EmptyBorder(7,10,8,10));
        nav.setLayout(new BoxLayout(nav,BoxLayout.Y_AXIS));
        JScrollPane navScroll=new JScrollPane(nav);
        navScroll.setBorder(null);
        navScroll.getVerticalScrollBar().setUnitIncrement(14);
        navScroll.setHorizontalScrollBarPolicy(ScrollPaneConstants.HORIZONTAL_SCROLLBAR_NEVER);
        sidebar.add(navScroll,BorderLayout.CENTER);
        JPanel bottom=new JPanel();
        bottom.setBackground(Theme.NAV);
        bottom.setBorder(new EmptyBorder(13,15,18,15));
        bottom.setLayout(new BoxLayout(bottom,BoxLayout.Y_AXIS));
        JPanel profile=new JPanel(new BorderLayout(9,0));
        profile.setOpaque(false);
        JLabel avatar=Theme.label("  "+role.name.substring(0,1).toUpperCase()+"  ",18,true,Color.WHITE);
        avatar.setOpaque(true);
        avatar.setBackground(Theme.TEAL);
        avatar.setBorder(new EmptyBorder(10,4,10,4));
        profile.add(avatar,BorderLayout.WEST);
        JPanel user=new JPanel(new GridLayout(2,1));
        user.setOpaque(false);
        JLabel userName=Theme.label(role.name,13,true,Color.WHITE);
        JLabel userRole=Theme.label(role.title,11,false,Theme.MINT);
        user.add(userName);
        user.add(userRole);
        profile.add(user,BorderLayout.CENTER);
        bottom.add(profile);
        bottom.add(Box.createVerticalStrut(15));
        JButton out=Theme.button("Đăng xuất",new Color(0x28464A),Theme.CREAM);
        out.setMaximumSize(new Dimension(Integer.MAX_VALUE,38));
        out.setAlignmentX(Component.CENTER_ALIGNMENT);
        out.addActionListener(e->{
            dispose();new SignIn().setVisible(true);
        });
        bottom.add(out);
        sidebar.add(bottom,BorderLayout.SOUTH);
        add(sidebar,BorderLayout.WEST);
        JPanel main=new JPanel(new BorderLayout());
        main.setBackground(Theme.BG);
        JPanel header=new JPanel(new BorderLayout());
        header.setBackground(Color.WHITE);
        header.setBorder(new EmptyBorder(18,30,18,30));
        title=Theme.label("Tổng quan",18,true,Theme.NAV);
        header.add(title,BorderLayout.WEST);
        header.add(Theme.label("GARA THINKING AUTO    •    "+role.title,11,true,Theme.TEAL),BorderLayout.EAST);
        main.add(header,BorderLayout.NORTH);
        body=new JPanel(new BorderLayout());
        main.add(body,BorderLayout.CENTER);
        add(main,BorderLayout.CENTER);
        open("Tổng quan");
    }
    private void section(String label){
        nav.add(Box.createVerticalStrut(19));
        JLabel l=Theme.label("  "+label,10,true,Theme.MINT);
        l.setMaximumSize(new Dimension(220,22));
        nav.add(l);
        nav.add(Box.createVerticalStrut(9));
    }
    public void open(String page){
        current=page;
        title.setText(page);
        nav.removeAll();
        String[] items=MenuData.forRole(role);
        section("TỔNG QUAN");
        for(int i=0;i<items.length;i++){
            String s=items[i];
            if(i==1)section(role==Role.KY_THUAT?"XƯỞNG DỊCH VỤ":role==Role.KHO?"KHO PHỤ TÙNG":role==Role.THU_NGAN?"THU NGÂN":"QUẢN LÝ NGHIỆP VỤ");
            if(role==Role.QUAN_LY && s.equals("Thống kê"))section("BÁO CÁO");
            JButton b=new JButton(s);
            b.setIcon(Icons.get(s,17,s.equals(page)?Color.WHITE:new Color(0xB8D4D0)));
            b.setIconTextGap(12);
            b.setHorizontalAlignment(SwingConstants.LEFT);
            b.setMaximumSize(new Dimension(222,42));
            b.setPreferredSize(new Dimension(222,42));
            b.setFont(Theme.font(12,s.equals(page)));
            b.setFocusPainted(false);
            b.setBorder(new EmptyBorder(0,13,0,5));
            b.setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
            b.setBackground(s.equals(page)?Theme.TEAL:Theme.NAV);
            b.setForeground(s.equals(page)?Color.WHITE:new Color(0xD1DFDD));
            b.setOpaque(true);
            b.addActionListener(e->open(s));
            nav.add(b);
            nav.add(Box.createVerticalStrut(3));
        }
        nav.revalidate();
        nav.repaint();
        body.removeAll();
        JComponent view=page.equals("Tổng quan")?new DashboardPanel(role,this):page.equals("Hóa đơn")?new InvoicePanel():page.equals("Thanh toán")?new PaymentPanel():page.equals("Thống kê")?new StatisticsPanel():page.equals("Bán phụ tùng")?new PartsSalePanel():SpecialPanel.supports(page)?new SpecialPanel(page):new ObjectPanel(page);
        JScrollPane scroll=new JScrollPane(view, JScrollPane.VERTICAL_SCROLLBAR_AS_NEEDED, JScrollPane.HORIZONTAL_SCROLLBAR_NEVER);
        scroll.setBorder(null);
        scroll.getVerticalScrollBar().setUnitIncrement(20);
        body.add(scroll,BorderLayout.CENTER);
        body.revalidate();
        body.repaint();
    }
}
